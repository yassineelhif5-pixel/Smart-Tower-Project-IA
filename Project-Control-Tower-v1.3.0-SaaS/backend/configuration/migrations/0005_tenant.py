def drop_constraint(table, contype, referenced=None):
    """Supprime une contrainte dont Django a généré le nom (clé primaire « p » ou étrangère « f »)."""
    ref = f" and confrelid = '{referenced}'::regclass" if referenced else ""
    return f"""
do $$ declare c text; begin
  for c in select conname from pg_constraint
           where conrelid = '{table}'::regclass and contype = '{contype}'{ref} loop
    execute format('alter table {table} drop constraint %I', c);
  end loop;
end $$;"""


def tenant_column(table, backfill, required=True, on_delete="restrict"):
    sql = [
        f"alter table {table} add column tenant_id bigint null;",
        f"update {table} set tenant_id = {backfill};",
        f"alter table {table} add constraint {table}_tenant_fk foreign key (tenant_id) "
        f"references tenants_tenant(id) deferrable initially deferred;",
        f"create index {table}_tenant_idx on {table} (tenant_id);",
    ]
    if required:
        sql.insert(2, f"alter table {table} alter column tenant_id set not null;")
    return "\n".join(sql)


